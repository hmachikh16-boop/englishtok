/**
 * Generate the IPA map used by the expanded curriculum.
 *
 * The app ships a static map instead of a phonemizer so the browser bundle
 * stays small and deterministic. Re-run this script whenever vocabulary is
 * added or changed:
 *
 *   npm run content:ipa
 */
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { phonemize } from 'phonemizer';
import { EXPANSION_LESSONS } from '../src/data/curriculumExpansion';

const normalizeKey = (word: string) => word.trim().toLowerCase().replace(/\s+/g, ' ');

const sourceByKey = new Map<string, string>();
for (const lesson of EXPANSION_LESSONS) {
  for (const word of lesson.words) {
    const key = normalizeKey(word[0]);
    if (!sourceByKey.has(key)) sourceByKey.set(key, word[0].trim());
  }
}

const words = [...sourceByKey.keys()].sort((left, right) => left.localeCompare(right));

const pronunciations: Record<string, string> = {};
const missing: string[] = [];

for (const word of words) {
  // Keep the original casing for acronyms such as "AI"; key the map by the
  // lowercase form the runtime uses.
  const [ipa] = await phonemize(sourceByKey.get(word) ?? word, 'en-us');
  const value = ipa?.trim();
  if (value) {
    pronunciations[word] = `/${value}/`;
  } else {
    pronunciations[word] = '';
    missing.push(word);
  }
}

const target = resolve(process.cwd(), 'src', 'data', 'expansion', 'pronunciations.ts');
const header = `/**
 * IPA pronunciations for the expanded curriculum.
 *
 * Generated by \`npm run content:ipa\` (scripts/build-pronunciations.ts) from
 * the vocabulary in src/data/expansion. The map is keyed by the lowercase,
 * whitespace-normalized word or phrase.
 *
 * Do not edit by hand.
 */
export const PRONUNCIATIONS: Record<string, string> = `;

await writeFile(target, `${header}${JSON.stringify(pronunciations, null, 2)};\n`, 'utf8');

console.info(`[ipa] Wrote ${Object.keys(pronunciations).length} pronunciations to ${target}`);
if (missing.length) {
  console.warn(`[ipa] ${missing.length} words produced no phonemes: ${missing.join(', ')}`);
}

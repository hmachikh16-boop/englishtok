const collectGlossary = (
  paragraphs: StoryParagraph[],
  language: 'en' | 'fr',
): Record<string, string> => {
  const dictionary = SHARED_GLOSSARY[language];
  const text = paragraphs.map((paragraph) => paragraph[language]).join(' ').toLowerCase();
  const tokens = text.match(/[a-zà-öø-ÿœ]+(?:'[a-zà-öø-ÿœ]+)*/g) ?? [];
  const glossary: Record<string, string> = {};
  for (const raw of tokens) {
    const clean = raw.replace(/^(qu|l|d|j|n|s|c|m|t)'/, '');
    if (dictionary[clean] && !glossary[clean]) glossary[clean] = dictionary[clean];
  }
  return glossary;
};

